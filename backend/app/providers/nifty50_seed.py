"""Nifty50 seed universe (Section 15).

Loaded from `data/processed/nifty50_instruments.json`, generated by
`scripts/sync_instruments.py` against two live, official sources:
NSE's own Nifty50 constituent list and Upstox's instrument master. Re-run
that script periodically -- NSE rebalances Nifty50 semi-annually (Jan 31 /
Jul 31 cutoffs).

If that file hasn't been generated yet (fresh clone, sync not run), falls
back to a small hand-picked subset -- kept deliberately small rather than
guessing ISINs, per the "never invent data" hard rule (Section 43). Three of
this fallback's originally-hand-typed ISINs (KOTAKBANK, BAJFINANCE,
NESTLEIND) were caught wrong by cross-checking against the official NSE list
during development -- a real demonstration of why this shouldn't be
hand-maintained; run the sync script instead of trusting this fallback.
"""

import json
from dataclasses import dataclass

from app.core.config import DATA_DIR

INSTRUMENTS_JSON_PATH = DATA_DIR / "processed" / "nifty50_instruments.json"


@dataclass(frozen=True)
class SeedInstrument:
    symbol: str
    name: str
    isin: str
    sector: str
    instrument_key: str

    @property
    def yfinance_ticker(self) -> str:
        return f"{self.symbol}.NS"


