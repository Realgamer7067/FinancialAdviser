def _load_seed() -> list[SeedInstrument]:
    if not INSTRUMENTS_JSON_PATH.exists():
        return _FALLBACK_SEED
    data = json.loads(INSTRUMENTS_JSON_PATH.read_text())
    return [SeedInstrument(**row) for row in data["instruments"]]


NIFTY50_SEED: list[SeedInstrument] = _load_seed()
